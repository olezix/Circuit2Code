"""The README and the paper must agree with the JSON artefacts.

Every number in README section 9 and in the experiments section of the paper is
generated by ``scripts/render_report.py``; this test fails if somebody edits a
table by hand, or commits new artefacts without regenerating the prose.
"""

from __future__ import annotations

import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def test_generated_sections_are_up_to_date():
    result = subprocess.run(
        [sys.executable, os.path.join("scripts", "render_report.py"), "--check"],
        cwd=ROOT,
        capture_output=True,
        text=True,
    )
    assert result.returncode == 0, (
        "README/paper are stale with respect to artifacts/*.json\n"
        f"{result.stdout}{result.stderr}\n"
        "run: python scripts/render_report.py"
    )


def test_markers_are_present():
    for relative, begin, end in (
        ("README.md", "<!-- BEGIN GENERATED: results", "<!-- END GENERATED: results -->"),
        ("paper/main.tex", "% BEGIN GENERATED: experiments", "% END GENERATED: experiments"),
    ):
        with open(os.path.join(ROOT, relative), encoding="utf-8") as handle:
            text = handle.read()
        assert text.count(begin) == 1, relative
        assert text.count(end) == 1, relative
        assert text.index(begin) < text.index(end), relative


def test_version_is_consistent():
    """pyproject, the package, the citation file and the changelog agree."""
    import re

    import src

    with open(os.path.join(ROOT, "pyproject.toml"), encoding="utf-8") as handle:
        pyproject = handle.read()
    with open(os.path.join(ROOT, "CITATION.cff"), encoding="utf-8") as handle:
        citation = handle.read()
    with open(os.path.join(ROOT, "CHANGELOG.md"), encoding="utf-8") as handle:
        changelog = handle.read()

    version = re.search(r'^version = "([^"]+)"', pyproject, re.MULTILINE).group(1)
    assert version == src.__version__
    assert re.search(r"^version: (\S+)", citation, re.MULTILINE).group(1) == version
    assert f"## [{version}]" in changelog
