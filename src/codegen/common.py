def fmt_number(value: float, *, float_context: bool = False) -> str:
    """Format a float so that it round-trips and reads naturally."""
    value = float(value)
    if not math.isfinite(value):
        raise ValueError(f"cannot emit non-finite constant {value}")
    if float(value).is_integer() and abs(value) < 1e16:
        return f"{int(value)}.0" if float_context else str(int(value))
    text = repr(value)
    if not float_context and "e" not in text and "." in text:
        return text
    return text


def is_integer_program(expr: Expr) -> bool:
    """Whether an expression is built exclusively from exact integer operations.

    Such programs (``(a + b) % p``) are emitted with integer types, which makes
    the C output bit-exact by construction.  Everything else (trigonometry,
    softmax, argmax over real logits) is emitted in double precision.
    """
    if isinstance(expr, Const):
        return float(expr.value).is_integer()
    if isinstance(expr, Var):
        return True
    if isinstance(expr, Neg):
        return is_integer_program(expr.operand)
    if isinstance(expr, BinOp):
        return expr.op in ("+", "-", "*") and is_integer_program(expr.left) and is_integer_program(
            expr.right
        )
    if isinstance(expr, Mod):
        return is_integer_program(expr.operand)
    if isinstance(expr, Sum):
        return all(is_integer_program(t) for t in expr.terms)
    if isinstance(expr, IfElse):
        return is_integer_program(expr.then) and is_integer_program(expr.otherwise)
    return False


@dataclass
class HoistedNode:
    """A node that is emitted as its own local variable (softmax, linear map)."""

    node: Expr
    name: str
    children: List["HoistedNode"]


def plan_hoisting(root: Expr) -> Tuple[List[HoistedNode], Dict[int, HoistedNode]]:
    """Assign a local variable to every ``Softmax``/``Linear`` node.

    Returns the hoisted nodes in dependency order (children first) together with
    a lookup from ``id(node)`` to the assignment.
    """
    ordered: List[HoistedNode] = []
    lookup: Dict[int, HoistedNode] = {}
    counters = {"softmax": 0, "linear": 0}

    def visit(node: Expr) -> Optional[HoistedNode]:
        if id(node) in lookup:
            return lookup[id(node)]
        children = [c for c in (visit(child) for child in node.children()) if c is not None]
        if isinstance(node, Softmax):
            name = f"attn_{counters['softmax']}"
            counters["softmax"] += 1
            entry = HoistedNode(node=node, name=name, children=children)
            ordered.append(entry)
            lookup[id(node)] = entry
            return entry
        if isinstance(node, Linear):
            name = f"map_{counters['linear']}"
            counters["linear"] += 1
            entry = HoistedNode(node=node, name=name, children=children)
            ordered.append(entry)
            lookup[id(node)] = entry
            return entry
        return children[0] if children else None

    visit(root)
    return ordered, lookup


def program_docstring(program, *, header: str = "Circuit2Code") -> str:
    """Common docstring body shared by the emitters."""
    lines = [
        f"Auto-generated by {header} -- do not edit by hand.",
        "",
        f"Decompiled program ``{program.name}`` over Z_{program.p}.",
    ]
    if program.docstring:
        lines.append("")
        lines.extend(program.docstring.splitlines())
    motif = program.provenance.get("motif")
    if motif:
        lines.append("")
        lines.append(f"Identified algorithm: {motif}.")
    freqs = program.provenance.get("frequencies")
    if freqs:
        pretty = ", ".join(f"head {h}: {list(k)}" for h, k in freqs.items())
        lines.append(f"Learned Fourier frequencies -- {pretty}.")
    return "\n".join(lines)
